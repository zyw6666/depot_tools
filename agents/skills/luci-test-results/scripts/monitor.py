from find_cl_builds import (
    DEFAULT_GERRIT_HOST,
    _normalize_gerrit_host,
    find_cl_builds,
    get_current_branch_cl,
    parse_cl_arg,
)
import gerrit_util

EXIT_PASSED = 0
EXIT_ERROR = 3
EXIT_FAILED = 10
EXIT_NEW_PATCHSET = 11
EXIT_TIMEOUT = 12
EXIT_RUNNING = 13
EXIT_IDLE = 14

# Backoff intervals in seconds: checks at 5m, 10m, 20m, 40m, 80m, then every 20m
BACKOFF_INTERVALS_SEC = (300, 300, 600, 1200, 2400)
STEADY_INTERVAL_SEC = 1200
DEFAULT_TIMEOUT_SEC = 10800

FAILED_STATUSES = ("FAILURE", "INFRA_FAILURE", "CANCELED")
RUNNING_STATUSES = ("STARTED", "SCHEDULED")
TRIVIAL_REVISION_KINDS = ("NO_CHANGE", "NO_CODE_CHANGE", "TRIVIAL_REBASE")
CQ_TAG_PREFIXES = ("autogenerated:cq:", "autogenerated:cv:")


class _MonitorArgumentParser(argparse.ArgumentParser):
    """ArgumentParser that exits with EXIT_ERROR (3) instead of 2."""

    def error(self, message):
        self.print_usage(sys.stderr)
        self.exit(EXIT_ERROR, f"{self.prog}: error: {message}\n")


def _format_duration_short(seconds):
    """Formats seconds as a compact string like '5m' or '45s'."""
    seconds = max(0, int(round(seconds)))
    if seconds >= 60 and seconds % 60 == 0:
        return f"{seconds // 60}m"
    if seconds >= 60:
        return f"{seconds // 60}m{seconds % 60}s"
    return f"{seconds}s"


def fetch_gerrit_detail(cl_number, host=DEFAULT_GERRIT_HOST):
    """Fetches Gerrit change detail with revisions, labels, and messages."""
    norm_host = _normalize_gerrit_host(host)
    try:
        return gerrit_util.GetChangeDetail(
            norm_host,
            str(cl_number),
            ["ALL_REVISIONS", "DETAILED_LABELS", "MESSAGES"],
        )
    except (gerrit_util.GerritError, OSError, ValueError) as err:
        print(
            f"Error fetching Gerrit detail for CL {cl_number}: {err}",
            file=sys.stderr,
        )
        return None


def evaluate_gerrit_cq_state(detail):
    """Extracts patchset equivalence group and CQ verdict from Gerrit detail.

    Returns a dict with:
        latest_patchset: int or None
        effective_patchset: int or None
        cq_active: bool
        cq_verdict: 'PASSED', 'FAILED', 'RUNNING', or None
    """
    if not isinstance(detail, dict):
        return {
            "latest_patchset": None,
            "effective_patchset": None,
            "cq_active": False,
            "cq_verdict": None,
        }

    revisions = detail.get("revisions") or {}
    current_rev = detail.get("current_revision")
    latest_ps = None
    if current_rev and current_rev in revisions:
        latest_ps = int(revisions[current_rev]["_number"])
    elif revisions:
        latest_ps = max(int(r["_number"]) for r in revisions.values())

    equiv_ps = set()
    for rev_info in sorted(
        revisions.values(), key=lambda r: int(r["_number"]), reverse=True
    ):
        ps_num = int(rev_info["_number"])
        equiv_ps.add(ps_num)
        if rev_info.get("kind", "") not in TRIVIAL_REVISION_KINDS:
            break

    messages = detail.get("messages") or []
    cq_msgs = [
        m
        for m in messages
        if m.get("_revision_number") in equiv_ps
        and str(m.get("tag", "")).startswith(CQ_TAG_PREFIXES)
    ]

    effective_ps = latest_ps
    if cq_msgs:
        effective_ps = int(cq_msgs[-1]["_revision_number"])

    cq_votes = detail.get("labels", {}).get("Commit-Queue", {}).get("all") or []
    cq_active = any(int(v.get("value", 0)) in (1, 2) for v in cq_votes)

    if detail.get("status") == "MERGED":
        cq_verdict = "PASSED"
    elif cq_active:
        cq_verdict = "RUNNING"
    elif cq_msgs:
        last_text = str(cq_msgs[-1].get("message", "")).lower()
        if "passed the run" in last_text or "cl has passed" in last_text:
            cq_verdict = "PASSED"
        elif (
            "failed the run" in last_text
            or "cl has failed" in last_text
            or "cannot be submitted" in last_text
            or "tryjobs failed" in last_text
        ):
            cq_verdict = "FAILED"
        else:
            cq_verdict = None
    else:
        cq_verdict = None

    return {
        "latest_patchset": latest_ps,
        "effective_patchset": effective_ps,
        "cq_active": cq_active,
        "cq_verdict": cq_verdict,
    }


def _evaluate_single_cl(
    cl_item, patchset=None, host=None, initial_latest_ps=None
):
    """Evaluates a single CL's CQ state and non-experimental builds."""
    parsed_host, parsed_cl, parsed_ps = parse_cl_arg(cl_item)
    cl_display = parsed_cl or str(cl_item)
    effective_host = _normalize_gerrit_host(host or parsed_host)
    explicit_ps = patchset if patchset is not None else parsed_ps

    if not parsed_cl:
        return {
            "cl": cl_display,
            "host": effective_host,
            "patchset": explicit_ps,
            "latest_patchset": None,
            "status": "ERROR",
            "reason": "invalid_cl",
            "total": 0,
            "success": 0,
            "failed": 0,
            "running": 0,
            "builds": [],
        }

    detail = fetch_gerrit_detail(parsed_cl, host=effective_host)
    cq_state = evaluate_gerrit_cq_state(detail)
    latest_ps = cq_state["latest_patchset"]
    target_ps = (
        explicit_ps
        if explicit_ps is not None
        else cq_state["effective_patchset"]
    )

    if (
        initial_latest_ps is not None
        and latest_ps is not None
        and latest_ps > initial_latest_ps
    ):
        return {
            "cl": cl_display,
            "host": effective_host,
            "patchset": latest_ps,
            "latest_patchset": latest_ps,
            "status": "NEW_PATCHSET",
            "reason": "new_patchset_uploaded",
            "total": 0,
            "success": 0,
            "failed": 0,
            "running": 0,
            "builds": [],
        }

    jobs = find_cl_builds(
        parsed_cl,
        patchset=explicit_ps,
        host=effective_host,
        show_all=True,
        latest_only=True,
        include_experimental=False,
        return_none_on_error=True,
    )

    if jobs is None:
        return {
            "cl": cl_display,
            "host": effective_host,
            "patchset": target_ps,
            "latest_patchset": latest_ps,
            "status": "ERROR",
            "reason": "fetch_builds_error",
            "total": 0,
            "success": 0,
            "failed": 0,
            "running": 0,
            "builds": [],
        }

    resolved_ps = jobs[0].get("patchset", target_ps) if jobs else target_ps
    total = len(jobs)
    success = sum(1 for j in jobs if j["status"] == "SUCCESS")
    failed = sum(1 for j in jobs if j["status"] in FAILED_STATUSES)
    running = sum(1 for j in jobs if j["status"] in RUNNING_STATUSES)

    cq_verdict = cq_state["cq_verdict"]
    if cq_verdict == "PASSED":
        status = "PASSED"
        reason = "cq_passed"
    elif cq_verdict == "FAILED":
        status = "FAILED"
        reason = "cq_failed"
    elif failed > 0:
        status = "FAILED"
        reason = "unretried_builder_failure"
    elif cq_verdict == "RUNNING" or running > 0:
        status = "RUNNING"
        reason = "cq_running"
    elif total > 0 and success == total:
        status = "PASSED"
        reason = "all_builds_passed"
    else:
        status = "IDLE"
        reason = "no_active_cq_or_builds"

    return {
        "cl": cl_display,
        "host": effective_host,
        "patchset": resolved_ps,
        "latest_patchset": latest_ps,
        "status": status,
        "reason": reason,
        "total": total,
        "success": success,
        "failed": failed,
        "running": running,
        "builds": jobs,
    }


def _aggregate_summaries(summaries):
    """Determines overall result string and exit code across CL summaries."""
    statuses = [s["status"] for s in summaries]
    if not summaries or "ERROR" in statuses:
        return "ERROR", EXIT_ERROR
    if "NEW_PATCHSET" in statuses:
        return "NEW PATCHSET UPLOADED", EXIT_NEW_PATCHSET
    if "FAILED" in statuses:
        return "SOME JOBS FAILED", EXIT_FAILED
    if "RUNNING" in statuses:
        return "SOME JOBS STILL RUNNING", EXIT_RUNNING
    if all(st == "PASSED" for st in statuses):
        return "ALL JOBS PASSED", EXIT_PASSED
    return "IDLE (NO ACTIVE RUNS)", EXIT_IDLE


def _print_report(summaries, overall, exit_code, as_json=False):
    """Prints either the JSON payload or human-readable ASCII summary."""
    if as_json:
        print(
            json.dumps(
                {
                    "result": overall,
                    "exit_code": exit_code,
                    "cls": summaries,
                },
                indent=2,
            )
        )
        return

    print(
        f"{'CL':<10} | {'Status':<12} | "
        f"{'Jobs (Total/Success/Failed/Running)':<40}"
    )
    print("-" * 70)
    for s in summaries:
        cl_display = s["cl"]
        status = s["status"]
        if status in ("ERROR", "IDLE", "NEW_PATCHSET") and s["total"] == 0:
            print(f"{cl_display:<10} | {status:<12} | {'-':<40}")
            continue
        counts = f"{s['total']}/{s['success']}/{s['failed']}/{s['running']}"
        print(f"{cl_display:<10} | {status:<12} | {counts:<40}")
        if status != "PASSED":
            for j in s["builds"]:
                if j["status"] != "SUCCESS":
                    print(f"  - {j['builder']}: {j['status']} ({j['id']})")
    print("-" * 70)
    print(f"Result: {overall} (exit_code={exit_code})")


def monitor_cls(
    cl_list,
    patchset=None,
    host=None,
    as_json=False,
    once=False,
    timeout_sec=DEFAULT_TIMEOUT_SEC,
    backoff_intervals=BACKOFF_INTERVALS_SEC,
    steady_interval=STEADY_INTERVAL_SEC,
):
    """Monitors CQ try job status for one or more CLs and returns exit code.

    By default, blocks with exponential backoff (5m, 10m, 20m, 40m, 80m, then
    every 20m up to timeout_sec) until CQ finishes, a non-experimental builder
    fails without an active retry, or a new patchset is uploaded. Pass
    once=True for a single non-blocking snapshot.
    """
    if not cl_list:
        _print_report([], "ERROR", EXIT_ERROR, as_json=as_json)
        return EXIT_ERROR

    summaries = [
        _evaluate_single_cl(cl_item, patchset=patchset, host=host)
        for cl_item in cl_list
    ]
    overall, exit_code = _aggregate_summaries(summaries)

    if once or exit_code != EXIT_RUNNING:
        _print_report(summaries, overall, exit_code, as_json=as_json)
        return exit_code

    initial_latest = {s["cl"]: s.get("latest_patchset") for s in summaries}
    first_interval = (
        backoff_intervals[0] if backoff_intervals else steady_interval
    )
    next_str = _format_duration_short(first_interval)
    banner_stream = sys.stderr if as_json else sys.stdout
    for s in summaries:
        ps_label = s.get("patchset") or s.get("latest_patchset") or "?"
        print(
            f"watching CL {s['cl']} ({s['host']}, PS {ps_label}), "
            f"next check in {next_str}",
            file=banner_stream,
            flush=True,
        )

    elapsed = 0.0
    step_idx = 0
    last_good_summaries = summaries

    while elapsed < timeout_sec:
        interval = (
            backoff_intervals[step_idx]
            if step_idx < len(backoff_intervals)
            else steady_interval
        )
        sleep_sec = min(float(interval), float(timeout_sec - elapsed))
        if sleep_sec <= 0:
            break
        time.sleep(sleep_sec)
        elapsed += sleep_sec
        step_idx += 1

        polled = []
        for cl_item in cl_list:
            _, parsed_cl, _ = parse_cl_arg(cl_item)
            cl_key = parsed_cl or str(cl_item)
            polled.append(
                _evaluate_single_cl(
                    cl_item,
                    patchset=patchset,
                    host=host,
                    initial_latest_ps=initial_latest.get(cl_key),
                )
            )
        overall, exit_code = _aggregate_summaries(polled)

        # Ignore transient poll errors mid-watch unless timeout is reached.
        if exit_code == EXIT_ERROR:
            continue

        last_good_summaries = polled
        if exit_code != EXIT_RUNNING:
            _print_report(polled, overall, exit_code, as_json=as_json)
            return exit_code

    for s in last_good_summaries:
        if s["status"] == "RUNNING":
            s["status"] = "TIMEOUT"
            s["reason"] = "timeout"
    _print_report(last_good_summaries, "TIMEOUT", EXIT_TIMEOUT, as_json=as_json)
    return EXIT_TIMEOUT


def _crash_excepthook(exc_type, exc_value, exc_tb):
    """Maps any uncaught runtime exception to EXIT_ERROR (3)."""
    sys.__excepthook__(exc_type, exc_value, exc_tb)
    sys.exit(EXIT_ERROR)


def main():
    sys.excepthook = _crash_excepthook
    parser = _MonitorArgumentParser(
        description=(
            "Monitor the status of CQ try jobs for one or more Gerrit CLs."
        )
    )
    parser.add_argument(
        "cls",
        metavar="CL",
        nargs="*",
        help=(
            "Gerrit CL numbers or URLs to monitor. If omitted, uses the "
            "active branch's CL via `git cl issue`."
        ),
    )
    parser.add_argument(
        "--patchset",
        type=int,
        help="Optional patchset number (defaults to latest CQ run patchset)",
    )
    parser.add_argument(
        "--host",
        default=None,
        help=f"Gerrit host (default: {DEFAULT_GERRIT_HOST})",
    )
    parser.add_argument(
        "--once",
        action="store_true",
        help="Run a single status check and exit without polling",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=DEFAULT_TIMEOUT_SEC,
        help=(
            "Max seconds to wait before timeout "
            f"(default: {DEFAULT_TIMEOUT_SEC})"
        ),
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Emit structured JSON summary instead of ASCII table",
    )

    args = parser.parse_args()
    cl_list = list(args.cls)
    if not cl_list:
        current_cl = get_current_branch_cl()
        if current_cl:
            cl_list = [current_cl]
        else:
            if args.json:
                print(
                    json.dumps(
                        {
                            "result": "ERROR",
                            "exit_code": EXIT_ERROR,
                            "cls": [],
                        },
                        indent=2,
                    )
                )
            else:
                print(
                    "Error: No CLs specified and no active branch CL found.",
                    file=sys.stderr,
                )
            sys.exit(EXIT_ERROR)

    sys.exit(
        monitor_cls(
            cl_list,
            patchset=args.patchset,
            host=args.host,
            as_json=args.json,
            once=args.once,
            timeout_sec=args.timeout,
        )
    )


if __name__ == "__main__":
    main()
